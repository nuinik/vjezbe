package KrizicKruzic;

public class Igrac {

    private String ime;
    private char simbol;

    public Igrac(String ime, char simbol) {
        this.ime = ime;
        this.simbol = simbol;
    }

    public String getIme() {
        return ime;
    }

    public char getSimbol() {
        return simbol;
    }
}
